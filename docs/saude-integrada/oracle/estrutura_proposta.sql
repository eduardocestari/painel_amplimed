-- Uma linha fixa serializa a conclusao de lotes e torna NR_CONCLUSAO monotonico.
CREATE TABLE UDBNU_AMPLIMED_CONTROLE (
  CHAVE                 NUMBER(1) CONSTRAINT PK_SI_CONTROLE PRIMARY KEY,
  NR_ULTIMA_CONCLUSAO   NUMBER(19) DEFAULT 0 NOT NULL,
  CONSTRAINT CK_SI_CONTROLE_CHAVE CHECK (CHAVE = 1)
);

CREATE TABLE UDBNU_AMPLIMED_IMPORTACOES (
  ID_LOTE               VARCHAR2(36 CHAR) CONSTRAINT PK_SI_LOTE PRIMARY KEY,
  NR_CONCLUSAO          NUMBER(19),
  DT_INICIO             TIMESTAMP(6) WITH TIME ZONE DEFAULT SYSTIMESTAMP NOT NULL,
  DT_CONCLUSAO          TIMESTAMP(6) WITH TIME ZONE,
  USUARIO_AD            VARCHAR2(200 CHAR) NOT NULL,
  ARQUIVO_SHA256        VARCHAR2(64 CHAR) NOT NULL,
  QT_LINHAS             NUMBER(10) DEFAULT 0 NOT NULL,
  QT_CPF_INVALIDO       NUMBER(10) DEFAULT 0 NOT NULL,
  QT_DATAS_INVALIDAS    NUMBER(10) DEFAULT 0 NOT NULL,
  QT_IDS_NUMERICOS      NUMBER(10) DEFAULT 0 NOT NULL,
  SITUACAO_LOTE         VARCHAR2(20 CHAR) NOT NULL,
  ERRO_CODIGO           VARCHAR2(50 CHAR),
  CONSTRAINT UK_SI_LOTE_ORDEM UNIQUE (NR_CONCLUSAO),
  CONSTRAINT CK_SI_LOTE_STATUS CHECK (SITUACAO_LOTE IN ('PROCESSANDO', 'CONCLUIDO', 'FALHOU')),
  CONSTRAINT CK_SI_LOTE_CONCLUIDO CHECK (
    SITUACAO_LOTE <> 'CONCLUIDO' OR
    (NR_CONCLUSAO IS NOT NULL AND DT_CONCLUSAO IS NOT NULL AND QT_LINHAS > 0)
  )
);

CREATE TABLE UDBNU_USUARIOS_AMPLIMED (
  ID_REGISTRO           NUMBER(19) GENERATED ALWAYS AS IDENTITY CONSTRAINT PK_SI_USUARIO PRIMARY KEY,
  ID_LOTE               VARCHAR2(36 CHAR) NOT NULL,
  LINHA_EXCEL           NUMBER(10) NOT NULL,
  NOME                  VARCHAR2(300 CHAR),
  EMAIL                 VARCHAR2(320 CHAR),
  CPF_BRUTO             VARCHAR2(100 CHAR),
  CPF_NUMERICO          VARCHAR2(11 CHAR),
  CPF_VALIDO            CHAR(1 CHAR) DEFAULT 'N' NOT NULL,
  CRM                   VARCHAR2(100 CHAR),
  ESPECIALIDADE         VARCHAR2(250 CHAR),
  PERMISSAO             VARCHAR2(100 CHAR),
  PERFIL                VARCHAR2(100 CHAR),
  SITUACAO              VARCHAR2(100 CHAR),
  DATA_CRIACAO_ORIGINAL VARCHAR2(100 CHAR),
  DT_CRIACAO            DATE,
  CLINICA               VARCHAR2(500 CHAR),
  CLINICA_CHAVE         VARCHAR2(500 CHAR),
  USUCLIN               VARCHAR2(100 CHAR),
  ULTIMO_LOGIN_ORIGINAL VARCHAR2(100 CHAR),
  DT_ULTIMO_LOGIN       DATE,
  CONSTRAINT FK_SI_USUARIO_LOTE FOREIGN KEY (ID_LOTE) REFERENCES UDBNU_AMPLIMED_IMPORTACOES (ID_LOTE),
  CONSTRAINT UK_SI_LOTE_LINHA UNIQUE (ID_LOTE, LINHA_EXCEL),
  CONSTRAINT CK_SI_CPF_VALIDO CHECK (CPF_VALIDO IN ('S', 'N')),
  CONSTRAINT CK_SI_CPF_NORMALIZADO CHECK (CPF_VALIDO = 'N' OR CPF_NUMERICO IS NOT NULL)
);

-- UK_SI_LOTE_LINHA ja cria indice com prefixo ID_LOTE; nao criar indice redundante.
CREATE INDEX IX_SI_USUARIO_CLINICA ON UDBNU_USUARIOS_AMPLIMED (ID_LOTE, CLINICA_CHAVE);

-- A view nunca escolhe PROCESSANDO ou FALHOU. NR_CONCLUSAO e unico e
-- atualizado sob bloqueio da linha de controle, na mesma transacao dos usuarios.
CREATE OR REPLACE VIEW VW_UDBNU_USUARIOS_AMPLIMED_ATUAL AS
SELECT u.*
  FROM UDBNU_USUARIOS_AMPLIMED u
  JOIN UDBNU_AMPLIMED_IMPORTACOES l ON l.ID_LOTE = u.ID_LOTE
 WHERE l.SITUACAO_LOTE = 'CONCLUIDO'
   AND l.NR_CONCLUSAO = (
     SELECT MAX(x.NR_CONCLUSAO)
       FROM UDBNU_AMPLIMED_IMPORTACOES x
      WHERE x.SITUACAO_LOTE = 'CONCLUIDO'
   );

-- Executar uma vez, junto com a criacao inicial, apos revisao do DBA.
