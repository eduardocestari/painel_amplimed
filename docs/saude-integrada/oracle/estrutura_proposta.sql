CREATE TABLE UDBNU_AMPLIMED_IMPORTACOES (
  ID_LOTE          VARCHAR2(36) PRIMARY KEY,
  DT_INICIO        TIMESTAMP(6) DEFAULT SYSTIMESTAMP NOT NULL,
  DT_CONCLUSAO     TIMESTAMP(6),
  USUARIO_AD       VARCHAR2(200) NOT NULL,
  ARQUIVO_NOME     VARCHAR2(500),
  ARQUIVO_SHA256   VARCHAR2(64),
  QT_LINHAS        NUMBER(10),
  SITUACAO_LOTE    VARCHAR2(20) NOT NULL,
  ERRO_RESUMIDO    VARCHAR2(1000),
  CONSTRAINT CK_SI_LOTE_STATUS CHECK (SITUACAO_LOTE IN ('PROCESSANDO','CONCLUIDO','FALHOU'))
);

CREATE TABLE UDBNU_USUARIOS_AMPLIMED (
  ID_REGISTRO            NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  ID_LOTE                VARCHAR2(36) NOT NULL,
  LINHA_EXCEL            NUMBER(10) NOT NULL,
  NOME                   VARCHAR2(300),
  EMAIL                  VARCHAR2(320),
  CPF                    VARCHAR2(40),
  CPF_NUMERICO           VARCHAR2(11),
  CPF_VALIDO             CHAR(1) DEFAULT 'N' NOT NULL,
  CRM                    VARCHAR2(100),
  ESPECIALIDADE          VARCHAR2(250),
  PERMISSAO              VARCHAR2(100),
  PERFIL                 VARCHAR2(100),
  SITUACAO               VARCHAR2(100),
  DATA_CRIACAO_ORIGINAL  VARCHAR2(100),
  DT_CRIACAO             DATE,
  CLINICA                VARCHAR2(500),
  CLINICA_CHAVE          VARCHAR2(500),
  USUCLIN                VARCHAR2(100),
  ULTIMO_LOGIN_ORIGINAL  VARCHAR2(100),
  DT_ULTIMO_LOGIN        DATE,
  CONSTRAINT FK_SI_USUARIOS_LOTE FOREIGN KEY (ID_LOTE) REFERENCES UDBNU_AMPLIMED_IMPORTACOES(ID_LOTE),
  CONSTRAINT UK_SI_LOTE_LINHA UNIQUE (ID_LOTE, LINHA_EXCEL),
  CONSTRAINT CK_SI_CPF_VALIDO CHECK (CPF_VALIDO IN ('S','N'))
);

CREATE INDEX IX_SI_USUARIOS_LOTE ON UDBNU_USUARIOS_AMPLIMED (ID_LOTE);
CREATE INDEX IX_SI_USUARIOS_CLINICA ON UDBNU_USUARIOS_AMPLIMED (ID_LOTE, CLINICA_CHAVE);

-- A consulta atual ignora lotes ainda PROCESSANDO ou FALHOU.
CREATE OR REPLACE VIEW VW_UDBNU_USUARIOS_AMPLIMED_ATUAL AS
SELECT u.*
FROM UDBNU_USUARIOS_AMPLIMED u
JOIN UDBNU_AMPLIMED_IMPORTACOES l ON l.ID_LOTE = u.ID_LOTE
WHERE l.ID_LOTE = (
  SELECT ID_LOTE FROM (
    SELECT x.ID_LOTE FROM UDBNU_AMPLIMED_IMPORTACOES x
    WHERE x.SITUACAO_LOTE = 'CONCLUIDO'
    ORDER BY x.DT_CONCLUSAO DESC, x.ID_LOTE DESC
  ) WHERE ROWNUM = 1
);

-- Consultas indicativas; ajustar para filtros, permissoes e performance.
SELECT COUNT(*) AS REGISTROS,
       COUNT(DISTINCT CLINICA_CHAVE) AS CLINICAS,
       COUNT(DISTINCT CASE WHEN CPF_VALIDO='S' AND UPPER(TRIM(PERMISSAO))='MÉDICO' THEN CPF_NUMERICO END) AS MEDICOS_UNICOS
FROM VW_UDBNU_USUARIOS_AMPLIMED_ATUAL;

SELECT MIN(CLINICA) AS CLINICA,
       COUNT(*) AS REGISTROS,
       COUNT(DISTINCT CASE WHEN CPF_VALIDO='S' AND UPPER(TRIM(PERMISSAO))='MÉDICO' THEN CPF_NUMERICO END) AS MEDICOS_UNICOS
FROM VW_UDBNU_USUARIOS_AMPLIMED_ATUAL
GROUP BY CLINICA_CHAVE
ORDER BY MEDICOS_UNICOS DESC, CLINICA;

