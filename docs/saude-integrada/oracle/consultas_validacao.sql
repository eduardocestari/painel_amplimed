-- CONSULTAS SOMENTE LEITURA, para executar apos a criacao aprovada pelo DBA.
-- Executar no esquema proprietario ou qualificar os nomes com o esquema aprovado.
-- Nao exibe CPF ou email. CPFs validos dependem da verificacao feita na aplicacao.

-- 1. Lote corrente: somente o maior numero de conclusao confirmado.
SELECT ID_LOTE, NR_CONCLUSAO, DT_INICIO, DT_CONCLUSAO, USUARIO_AD,
       QT_LINHAS, QT_CPF_INVALIDO, QT_DATAS_INVALIDAS, QT_IDS_NUMERICOS
  FROM UDBNU_AMPLIMED_IMPORTACOES
 WHERE SITUACAO_LOTE = 'CONCLUIDO'
   AND NR_CONCLUSAO = (
     SELECT MAX(NR_CONCLUSAO)
       FROM UDBNU_AMPLIMED_IMPORTACOES
      WHERE SITUACAO_LOTE = 'CONCLUIDO'
   );

-- 2. Indicadores da visao corrente. Clinica vazia conta como um grupo.
SELECT COUNT(*) AS REGISTROS,
       COUNT(DISTINCT CLINICA_CHAVE)
         + CASE WHEN COUNT(*) > COUNT(CLINICA_CHAVE) THEN 1 ELSE 0 END AS CLINICAS,
       COUNT(DISTINCT CASE
         WHEN CPF_VALIDO = 'S' AND UPPER(TRIM(PERMISSAO)) IN ('MÉDICO', 'MEDICO')
         THEN CPF_NUMERICO END) AS MEDICOS_UNICOS_COM_CPF_VALIDO,
       COUNT(DISTINCT CASE WHEN CPF_VALIDO = 'S' THEN CPF_NUMERICO END) AS PESSOAS_COM_CPF_VALIDO,
       NVL(SUM(CASE WHEN CPF_VALIDO = 'N' THEN 1 ELSE 0 END), 0) AS LINHAS_COM_CPF_INVALIDO
  FROM VW_UDBNU_USUARIOS_AMPLIMED_ATUAL;

-- 3. Medicos unicos com CPF valido e demais contagens por clinica.
SELECT CLINICA_CHAVE, MIN(CLINICA) AS NOME_ORIGINAL_EXEMPLO,
       COUNT(*) AS REGISTROS,
       COUNT(DISTINCT CASE WHEN CPF_VALIDO = 'S' THEN CPF_NUMERICO END) AS PESSOAS_COM_CPF_VALIDO,
       COUNT(DISTINCT CASE
         WHEN CPF_VALIDO = 'S' AND UPPER(TRIM(PERMISSAO)) IN ('MÉDICO', 'MEDICO')
         THEN CPF_NUMERICO END) AS MEDICOS_UNICOS_COM_CPF_VALIDO,
       MAX(DT_ULTIMO_LOGIN) AS ULTIMO_LOGIN_VALIDO
  FROM VW_UDBNU_USUARIOS_AMPLIMED_ATUAL
 GROUP BY CLINICA_CHAVE
 ORDER BY MEDICOS_UNICOS_COM_CPF_VALIDO DESC, NOME_ORIGINAL_EXEMPLO;

-- 4. Distribuicao por especialidade: CPF valido distinto dentro de cada categoria.
-- A soma entre categorias pode superar o total global se uma pessoa tiver mais de uma especialidade.
SELECT ESPECIALIDADE,
       COUNT(DISTINCT CPF_NUMERICO) AS MEDICOS_UNICOS_NA_ESPECIALIDADE
  FROM VW_UDBNU_USUARIOS_AMPLIMED_ATUAL
 WHERE CPF_VALIDO = 'S'
   AND UPPER(TRIM(PERMISSAO)) IN ('MÉDICO', 'MEDICO')
 GROUP BY ESPECIALIDADE
 ORDER BY MEDICOS_UNICOS_NA_ESPECIALIDADE DESC, ESPECIALIDADE;

-- 5. Situacao: preservar os valores originais, sem categorias presumidas.
SELECT SITUACAO, COUNT(*) AS REGISTROS
  FROM VW_UDBNU_USUARIOS_AMPLIMED_ATUAL
 GROUP BY SITUACAO
 ORDER BY REGISTROS DESC, SITUACAO;

-- 6. Historico auditavel, sem dados pessoais da planilha.
SELECT ID_LOTE, NR_CONCLUSAO, DT_INICIO, DT_CONCLUSAO, USUARIO_AD,
       QT_LINHAS, SITUACAO_LOTE, ERRO_CODIGO, ARQUIVO_SHA256
  FROM UDBNU_AMPLIMED_IMPORTACOES
 ORDER BY DT_INICIO DESC, ID_LOTE DESC;

-- 7. Conciliacao entre a contagem da view e a quantidade declarada no lote corrente.
SELECT l.ID_LOTE, l.QT_LINHAS AS LINHAS_DECLARADAS,
       (SELECT COUNT(*) FROM VW_UDBNU_USUARIOS_AMPLIMED_ATUAL) AS LINHAS_NA_VIEW
  FROM UDBNU_AMPLIMED_IMPORTACOES l
 WHERE l.SITUACAO_LOTE = 'CONCLUIDO'
   AND l.NR_CONCLUSAO = (
     SELECT MAX(NR_CONCLUSAO)
       FROM UDBNU_AMPLIMED_IMPORTACOES
      WHERE SITUACAO_LOTE = 'CONCLUIDO'
   );
